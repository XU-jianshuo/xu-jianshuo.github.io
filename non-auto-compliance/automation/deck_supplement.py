def _norm_status(title, raw=''):
    if '2026年第2号' in title:
        return '执行中'
    if '2025〕144号' in title:
        return '现行政策'
    if '指导意见' in title or '通知' in title:
        return '政策指导' if '绿色保险' in title or '新市民' in title or '普惠保险' in title else '执行中'
    return '现行有效'


def _kind_for(title, issuer):
    if '中华人民共和国' in title or '条例' in title or '管理办法' in title or '规定' in title:
        if issuer in ('国务院', '全国人大常委会') or '令' in title or '法' in title:
            return '法律依据'
    if any(x in issuer for x in ('教育部', '交通运输部', '国家体育总局', '文化和旅游部', '财政部', '工业和信息化部')):
        return '关联行业制度'
    if '国家互联网信息办公室' in issuer:
        return '数据制度'
    return '管理制度'


def _effective_for(title, row):
    if '绿色保险高质量发展' in title:
        return '自发布后执行'
    return row.get('effective') or row.get('date') or ''


